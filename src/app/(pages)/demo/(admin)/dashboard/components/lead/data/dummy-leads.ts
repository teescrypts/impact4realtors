// Helper functions for dummy data
export const getLeadsByCategory = (category: LeadCategory): Lead[] => {
  return DUMMY_LEADS.filter((lead) => lead.category === category);
};

export const getLeadsByStatus = (status: string): Lead[] => {
  return DUMMY_LEADS.filter((lead) => lead.status === status);
};

export const getLeadsInJourney = (): Lead[] => {
  return DUMMY_LEADS.filter((lead) => lead.currentJourney);
};

export const getLeadsWithoutJourney = (): Lead[] => {
  return DUMMY_LEADS.filter((lead) => !lead.currentJourney);
};

export const getActiveJourneyLeads = (): Lead[] => {
  return DUMMY_LEADS.filter(
    (lead) => lead.journeyProgress?.status === "active"
  );
};

export const getCompletedJourneyLeads = (): Lead[] => {
  return DUMMY_LEADS.filter(
    (lead) => lead.journeyProgress?.status === "completed"
  );
};
